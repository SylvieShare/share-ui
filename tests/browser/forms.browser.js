import {test,expect} from '@playwright/test'
for (const width of [390,834,1440]) test(`filled forms retain focus, live input and dashed actions at ${width}`,async({page})=>{
 await page.setViewportSize({width,height:1000})
 await page.goto('/tests/browser/forms.html')
 const input=page.getByRole('textbox',{name:'Name',exact:true})
 await expect(input).toHaveCSS('border-top-width','0px')
 const initial=await input.evaluate(el=>getComputedStyle(el).backgroundColor)
 await input.focus()
 await expect.poll(()=>input.evaluate(el=>getComputedStyle(el).backgroundColor)).not.toBe(initial)
 await input.fill('Draft')
 await expect(input).toHaveValue('Draft')
 await expect(page.getByRole('textbox',{name:'Invalid',exact:true})).not.toHaveCSS('background-color',initial)
 const number=page.locator('.fn-input')
 await number.fill('17')
 await expect(page.getByTestId('value')).toHaveText('17')
 const count=await page.getByTestId('calls').textContent()
 await number.blur()
 await expect(page.getByTestId('calls')).toHaveText(count)
 await expect(page.locator('.fn-wrap')).toHaveCSS('box-shadow',/0px 0px 0px 0px/)
 await expect(page.getByRole('button',{name:'Secondary',exact:true})).toHaveCSS('border-top-width','0px')
 await expect(page.getByRole('button',{name:'Icon toggle',exact:true})).toHaveCSS('border-top-width','0px')
 await expect(page.locator('.form-select')).toHaveCSS('border-top-width','0px')
 await expect(page.locator('.form-textarea')).toHaveCSS('border-top-width','0px')
 await expect(page.getByRole('button',{name:'Add entry',exact:true})).toHaveCSS('border-top-style','dashed')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
})
