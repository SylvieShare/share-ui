test('swipe closes only a leftward horizontal gesture when enabled', async ({ page }) => {
  await openDrawer(page, 'swipe')
  const surface = page.locator('#swipe-surface')
  async function gesture(points) {
    await surface.evaluate((el, points) => {
      const touch = point => new Touch({ identifier: 1, target: el, clientX: point[0], clientY: point[1] })
      el.dispatchEvent(new TouchEvent('touchstart', { touches: [touch(points[0])], bubbles: true }))
      el.dispatchEvent(new TouchEvent('touchmove', { touches: [touch(points[1])], bubbles: true, cancelable: true }))
      el.dispatchEvent(new TouchEvent('touchend', { changedTouches: [touch(points[1])], bubbles: true }))
    }, points)
  }
  await gesture([[250, 100], [240, 250]])
  await expect(dialog(page)).toBeVisible()
  await gesture([[250, 100], [100, 105]])
  await expect(dialog(page)).toHaveCount(0)
})

for (const breakpoint of [600, 640, 768, 1200]) {
  test(`sidebar and shell switch together at ${breakpoint}px in hide/top modes`, async ({ page }) => {
    const mobileMax = [600, 1200].includes(breakpoint) ? breakpoint - 1 : breakpoint
    for (const mobileMode of ['hide', 'top']) {
      await page.setViewportSize({ width: mobileMax + 1, height: 800 })
      await page.goto(`/tests/browser/?navigation&breakpoint=${breakpoint}&mobileMode=${mobileMode}`)
      const sidebar = page.locator('.share-app-sidebar')
      await expect(sidebar).toBeVisible()
      await expect(sidebar).toHaveCSS('width', '224px')
      await expect(page.locator('.share-sidebar-group')).toBeVisible()
      await expect(page.locator('.share-app-shell__rail')).toBeVisible()
      await page.setViewportSize({ width: mobileMax, height: 800 })
      await expect(page.locator('.share-app-shell__rail')).toBeHidden()
      if (mobileMode === 'hide') await expect(sidebar).toBeHidden()
      else {
        await expect(sidebar).toHaveCSS('flex-direction', 'row')
        await expect(page.locator('.share-sidebar-group')).toBeHidden()
        await expect(page.locator('.share-sidebar-link').nth(1).locator('.share-sidebar-label')).toBeHidden()
        await expect(page.locator('.share-sidebar-account')).toBeHidden()
      }
    }
  })
}

test('disabled breakpoint keeps desktop geometry at phone width; 600 yields a tablet rail', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 720 })
  await page.goto('/tests/browser/?navigation&breakpoint=0&mobileMode=top')
  await expect(page.locator('.share-app-sidebar')).toHaveCSS('width', '224px')
  await expect(page.locator('.share-app-sidebar')).toHaveCSS('flex-direction', 'column')
  await expect(page.locator('.share-sidebar-group')).toBeVisible()
  await expect(page.locator('.share-sidebar-account')).toBeVisible()
  await page.setViewportSize({ width: 900, height: 800 })
  await page.goto('/tests/browser/?navigation&breakpoint=600&collapsed&noToggle')
  await expect(page.locator('.share-app-sidebar')).toHaveCSS('width', '64px')
  await expect(page.locator('.share-sidebar-tools')).toHaveCount(0)
  const account = await page.locator('.share-sidebar-account').boundingBox()
  const sidebar = await page.locator('.share-app-sidebar').boundingBox()
  expect(account.y + account.height).toBe(sidebar.y + sidebar.height)
  await expect(page.locator('.share-app-shell__content')).toHaveCSS('margin-left', '0px')
  expect((await page.locator('.share-app-shell__content').boundingBox()).x).toBe(64)
  await page.setViewportSize({ width: 600, height: 800 })
  await expect(page.locator('.share-app-sidebar')).toBeVisible()
  await page.setViewportSize({ width: 599, height: 800 })
  await expect(page.locator('.share-app-sidebar')).toBeHidden()
  expect((await page.locator('.share-app-shell__content').boundingBox()).x).toBe(0)
})

