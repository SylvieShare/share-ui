import { test, expect } from '@playwright/test'

const dialog = page => page.getByRole('dialog', { name: 'Test drawer', exact: true })
const overflow = page => page.evaluate(() => document.documentElement.style.overflow)
async function openDrawer(page, query = '') {
  await page.goto(`/tests/browser/?${query}`)
  await page.locator('#opener').click()
  await expect(dialog(page)).toBeVisible()
  await expect.poll(() => page.evaluate(() => window.fixture.opened.value)).toBe(1)
}

test('focus, Tab loop, input Escape, immediate inert, scroll lock and focus return', async ({ page }) => {
  await page.goto('/tests/browser/')
  await page.evaluate(() => { document.documentElement.style.overflow = 'scroll' })
  await page.locator('#opener').click()
  const close = dialog(page).getByRole('button', { name: 'Close', exact: true })
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(page.locator('#drawer-last')).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.locator('#background').evaluate(el => el.focus())
  await expect(close).toBeFocused()
  await page.locator('#drawer-input').focus()
  await expect.poll(() => overflow(page)).toBe('hidden')
  await page.keyboard.press('Escape')
  // The outgoing DOM remains for the slide, but is immediately inaccessible.
  const layer = page.locator('.share-drawer')
  await expect(layer).toHaveAttribute('inert', '')
  await expect(layer).toHaveCSS('pointer-events', 'none')
  await expect.poll(() => overflow(page)).toBe('hidden')
  await expect(layer).toHaveCount(0)
  await expect.poll(() => overflow(page)).toBe('scroll')
  await expect(page.locator('#opener')).toBeFocused()
  expect(await page.evaluate(() => window.fixture.closed.value)).toBe(1)
})

