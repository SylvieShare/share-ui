import { test, expect } from '@playwright/test'
test('built blur API keeps standard filters, updates and pointer access', async ({ page }) => {
  await page.goto('/tests/browser/blur.html')
  const backdrop = page.locator('.tested-backdrop')
  await expect(backdrop).toHaveCSS('backdrop-filter', 'blur(8px)')
  await expect(backdrop).toHaveAttribute('aria-hidden', 'true')
  await expect(backdrop).toHaveCSS('pointer-events', 'none')
  await page.getByRole('button', { name: 'Background action' }).click()
  await expect(page.getByLabel('Clicks')).toHaveText('1')
  await page.getByRole('button', { name: 'Radius 16' }).click()
  await expect(backdrop).toHaveCSS('backdrop-filter', 'blur(16px)')
  await page.getByRole('button', { name: 'Radius 0' }).click()
  await expect(backdrop).toHaveCSS('backdrop-filter', 'blur(0px)')
  await expect(page.locator('.tested-glass')).toHaveCSS('backdrop-filter', 'blur(14px)')
  await page.getByRole('button', { name: 'Solid surface' }).click()
  await expect(page.locator('.tested-glass')).toHaveCSS('backdrop-filter', 'none')
  const open = page.getByRole('button', { name: 'Open modal' })
  await open.click()
  await expect(page.getByText('Modal opened', { exact: true })).toBeVisible()
  await expect(page.locator('.am-overlay')).toHaveCSS('backdrop-filter', 'blur(6px)')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(open).toBeFocused()
})
