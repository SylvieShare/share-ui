import { expect, test } from '@playwright/test'
test.use(process.env.SHARE_UI_BROWSER_EXECUTABLE ? { launchOptions: { executablePath: process.env.SHARE_UI_BROWSER_EXECUTABLE } } : {})

test('bounded fitting reacts to resize, content and visibility while preserving one child instance', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/tests/browser/fit-content.html')
  const owner = page.locator('[data-fit-owner]')
  await expect(owner).toHaveCount(1)
  await expect.poll(() => owner.getAttribute('data-fit-scale')).not.toBeNull()
  const ratio = () => owner.getAttribute('data-fit-scale').then(Number)
  expect(await ratio()).toBeGreaterThan(.5)
  expect(await ratio()).toBeLessThan(1)
  await expect(owner).toHaveAttribute('data-fit-wrapping', 'false')
  await page.getByRole('button', { name: 'Action' }).click()
  expect(await page.evaluate(() => window.fitState.clicks)).toBe(1)
  expect(await page.evaluate(() => window.fitState.mounts)).toBe(1)
  await page.evaluate(() => { window.fitState.width = 70 })
  await expect(owner).toHaveAttribute('data-fit-wrapping', 'true')
  expect(await ratio()).toBe(.5)
  expect(await owner.evaluate(el => el.firstElementChild.getBoundingClientRect().right <= el.getBoundingClientRect().right + 1)).toBe(true)
  await page.evaluate(() => { window.fitState.width = 400 })
  await expect.poll(ratio).toBe(1)
  await expect(owner).toHaveAttribute('data-fit-wrapping', 'false')
  await page.evaluate(() => { window.fitState.visible = false; window.fitState.count = 14 })
  await page.waitForTimeout(50)
  await page.evaluate(() => { window.fitState.visible = true })
  await expect.poll(ratio).toBeLessThan(1)
  expect(await ratio()).toBeGreaterThanOrEqual(.5)
  expect(await page.evaluate(() => window.fitState.mounts)).toBe(1)
  expect(errors).toEqual([])
})
